import * as vscode from 'vscode';

function validateName(name: string): string | undefined {
  if (!name || name.trim().length === 0) return 'Name cannot be empty';
  if (!/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(name.trim())) {
    return 'Name must be a valid C++ identifier (letters, digits, underscores; cannot start with a digit)';
  }
  return undefined;
}

function cppTemplate(name: string): string {
  return `#include "daisy_seed.h"
#include "daisysp.h"

using namespace daisy;
using namespace daisysp;

DaisySeed hardware;

// ds-ide:controls:begin
// Add controls here using the Wiring Editor (ds-ide: Open Wiring Editor)
// ds-ide:controls:end

void AudioCallback(AudioHandle::InputBuffer in,
                   AudioHandle::OutputBuffer out,
                   size_t size) {
    for (size_t i = 0; i < size; i++) {
        out[0][i] = in[0][i];
        out[1][i] = in[1][i];
    }
}

int main() {
    hardware.Init();
    hardware.StartAudio(AudioCallback);
    while (true) {}
}
`;
}

function cmakeTemplate(name: string): string {
  return `cmake_minimum_required(VERSION 3.15)
project(${name})
# This file satisfies the ds-ide effect-source auto-detection heuristic.
# The actual emulator build uses the CMakeLists.txt generated by Daisy IDE: Build for Emulator.
`;
}

const controllersYaml = `controllers:\n`;

function readmeTemplate(name: string): string {
  return `# ${name}

A ds-ide effect project.

## Getting started

1. Open this folder in VS Code with the Daisy Seed IDE extension installed.
2. Open the Wiring Editor (\`ds-ide: Open Wiring Editor\`) to add controls.
3. Build and run: use \`Daisy IDE: Build & Deploy to Emulator\` or press F5 with a \`ds-ide\` launch configuration.
`;
}

function enc(s: string): Uint8Array {
  return Buffer.from(s, 'utf8');
}

export async function createEffectProject(): Promise<void> {
  const rawName = await vscode.window.showInputBox({
    prompt: 'Effect project name',
    validateInput: validateName,
  });
  if (rawName === undefined) return;
  const name = rawName.trim();

  const picked = await vscode.window.showOpenDialog({
    canSelectFolders: true,
    canSelectFiles: false,
    canSelectMany: false,
    openLabel: 'Create here',
  });
  if (!picked?.[0]) return;

  const projectUri = vscode.Uri.joinPath(picked[0], name);

  try {
    await vscode.workspace.fs.stat(projectUri);
    void vscode.window.showErrorMessage(`ds-ide: folder already exists: ${projectUri.fsPath}`);
    return;
  } catch (err) {
    // FR-EXT-23: a blanket catch here previously treated ANY stat failure —
    // including a permission-denied or an unavailable-drive error — as "the
    // folder doesn't exist", proceeding to create it regardless. Only a
    // genuine not-found result means it's safe to proceed.
    const code = (err as { code?: unknown } | undefined)?.code;
    if (code !== 'FileNotFound' && code !== 'ENOENT') {
      const msg = err instanceof Error ? err.message : String(err);
      void vscode.window.showErrorMessage(
        `ds-ide: could not check destination folder ${projectUri.fsPath} — ${msg}`,
      );
      return;
    }
    // expected — folder does not exist yet
  }

  try {
    await vscode.workspace.fs.createDirectory(projectUri);
    await vscode.workspace.fs.writeFile(
      vscode.Uri.joinPath(projectUri, `${name}.cpp`),
      enc(cppTemplate(name)),
    );
    await vscode.workspace.fs.writeFile(
      vscode.Uri.joinPath(projectUri, 'CMakeLists.txt'),
      enc(cmakeTemplate(name)),
    );
    await vscode.workspace.fs.writeFile(
      vscode.Uri.joinPath(projectUri, 'controllers.yaml'),
      enc(controllersYaml),
    );
    await vscode.workspace.fs.writeFile(
      vscode.Uri.joinPath(projectUri, 'README.md'),
      enc(readmeTemplate(name)),
    );
  } catch (err) {
    void vscode.window.showErrorMessage(`ds-ide: failed to scaffold project: ${String(err)}`);
    return;
  }

  try {
    await vscode.commands.executeCommand('vscode.openFolder', projectUri, { forceNewWindow: false });
  } catch (err) {
    // FR-EXT-24: this was the only failure path in the function not wrapped
    // in try/catch — an unhandled rejection instead of the showErrorMessage
    // pattern every other step here uses.
    void vscode.window.showErrorMessage(`ds-ide: failed to open the new project folder: ${String(err)}`);
  }
}
